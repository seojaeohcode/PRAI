// prai — the command line. `npm run prai -- <command> <project> [options]`
import { spawn } from "node:child_process";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { beatValue } from "../src/engine/spec.ts";
import { frameOfBeat } from "../src/engine/beat.ts";
import { sayLines } from "../src/engine/timeline.ts";
import { analyzeBeats } from "./lib/beat-analyze.ts";
import { capture, type CapturePlan } from "./lib/capture.ts";
import { beatAlignment, lint, loudness } from "./lib/check.ts";
import { decodePcm, run } from "./lib/ffmpeg.ts";
import { ROOT, fileHash, load, outDir, saveLock, timeline, writeProps, type Project } from "./lib/project.ts";
import { KINDS, buildPrompt, runReview, type Kind } from "./lib/review.ts";
import { refsCommand } from "./lib/refs.ts";
import { writeGroove } from "./lib/synth.ts";
import { defaultVoice, synthesize, type VoiceConfig } from "./lib/tts.ts";

const argv = process.argv.slice(2);
const flags: Record<string, string | true> = {};
const pos: string[] = [];
for (let i = 0; i < argv.length; i++) {
  const a = argv[i];
  if (a.startsWith("--")) { const [k, v] = a.slice(2).split("="); flags[k] = v ?? (argv[i + 1] && !argv[i + 1].startsWith("--") ? argv[++i] : true); }
  else pos.push(a);
}
const [cmd, name] = pos;
const flag = (k: string, d?: string) => (typeof flags[k] === "string" ? (flags[k] as string) : d);
const fmt = (s: number) => `${Math.floor(s / 60)}:${(s % 60).toFixed(2).padStart(5, "0")}`;
const rel = (f: string) => path.relative(ROOT, f).replace(/\\/g, "/");

function remotion(args: string[]) {
  const cli = path.join(path.dirname(createRequire(import.meta.url).resolve("@remotion/cli/package.json")), "remotion-cli.js");
  return new Promise<void>((resolve, reject) => {
    const p = spawn(process.execPath, [cli, ...args], { cwd: ROOT, stdio: "inherit" });
    p.on("close", (c) => (c === 0 ? resolve() : reject(new Error(`remotion ${args[0]} failed (${c})`))));
  });
}

async function cmdMusic(p: Project) {
  const m = p.spec.music;
  if (!m) throw new Error("this project has no music block (silent video: nothing to do)");
  const file = path.join(p.pub, m.src);
  if (flags.synth || (!m.url && !fs.existsSync(file))) {
    const bpm = Number(flag("bpm", String(m.bpm ?? 120))), bars = Number(flag("bars", "48"));
    await writeGroove(file, { bpm, bars });
    console.log(`made a ${bpm} BPM, ${bars}-bar groove → ${rel(file)} (generated by PRAI, CC0)`);
  } else if (m.url && (!fs.existsSync(file) || flags.force)) {
    const r = await fetch(m.url);
    if (!r.ok) throw new Error(`download failed: ${r.status} ${m.url}`);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, Buffer.from(await r.arrayBuffer()));
    console.log(`downloaded ${m.url} → ${rel(file)}`);
    if (m.credit) console.log(`credit (put it in the video and the description): ${m.credit}`);
  } else console.log(`${rel(file)} is already there (--force to download again, --synth to generate a groove)`);
}

async function cmdBeat(p: Project) {
  const m = p.spec.music;
  if (!m) throw new Error("no music block");
  const file = path.join(p.pub, m.src);
  if (!fs.existsSync(file)) throw new Error(`missing ${rel(file)} — run: npm run prai -- music ${p.name}`);
  const a = analyzeBeats(await decodePcm(file, 22050, 120), 22050, { beatsPerBar: m.meter });
  p.lock.music = { file: m.src, ...a, hash: fileHash(file) };
  saveLock(p);
  console.log(`${m.src}: ${a.bpm} BPM, first beat ${a.offset}s, bar starts on beat ${a.downbeat + 1}, beat clarity ${a.clarity}${a.clarity < 2 ? " (weak — set music.bpm/offset by hand if the cut feels off)" : ""}`);
  if (m.bpm && Math.abs(m.bpm - a.bpm) > 0.3) console.log(`note: prai.json sets music.bpm=${m.bpm}, which wins over the measured ${a.bpm}`);
}

async function cmdVoice(p: Project) {
  const cfg = { ...p.spec.voice, voice: p.spec.voice.voice ?? defaultVoice(p.spec.video.lang) } as VoiceConfig, lead = beatValue(p.spec.voice.lead, p.spec.music?.meter ?? 4);
  const dir = path.join(p.pub, "voice"), next: NonNullable<typeof p.lock.voice> = {};
  for (const sc of p.spec.scenes) for (const l of sayLines(sc, lead, 4)) {
    const take = await synthesize(cfg, l.id, l.text, dir);
    next[l.id] = { file: take.file, text: take.text, seconds: take.seconds, cues: take.cues, hash: take.hash };
    console.log(`  ${l.id.padEnd(14)} ${take.seconds.toFixed(2)}s  ${l.text.slice(0, 60)}`);
  }
  p.lock.voice = next;
  saveLock(p);
  // remove takes no line uses any more
  const keep = new Set(Object.values(next).flatMap((v) => [v.file, v.file.replace(/\.\w+$/, ".srt")]));
  if (fs.existsSync(dir)) for (const f of fs.readdirSync(dir)) if (/^[0-9a-f]{12}\.(mp3|srt)$/.test(f) && !keep.has(f)) fs.rmSync(path.join(dir, f));
}

function planMarkdown(p: Project) {
  const tl = timeline(p), fps = tl.grid.fps, sec = (f: number) => f / fps, meter = tl.grid.beatsPerBar;
  const L: string[] = [`# Plan — ${p.spec.video.title}`, "", `${tl.grid.bpm} BPM · ${meter}/4 · ${fps} fps · ${tl.totalBeats} beats · ${fmt(sec(tl.totalFrames))}${tl.spec.music ? ` · song starts at ${tl.musicStart.toFixed(2)}s` : ""}`, "",
    "| # | scene | type | beats | starts | length | voice | headline |", "|---|---|---|---|---|---|---|---|"];
  for (const s of tl.scenes) {
    const v = s.voices.map((x) => `${x.id} ${x.seconds.toFixed(1)}s${x.estimated ? "*" : ""} @b${x.atBeat}`).join("<br>") || "—";
    const h = typeof s.scene.headline === "string" ? s.scene.headline : s.scene.headline?.text ?? "—";
    L.push(`| ${s.index + 1} | ${s.id} | ${s.scene.type} | ${s.beats} | b${s.start} · ${fmt(sec(s.from))} | ${sec(s.len).toFixed(2)}s | ${v} | ${h} |`);
  }
  L.push("", "`*` = estimated (not recorded yet).", "");
  for (const s of tl.scenes) {
    const rows: [number, string][] = [];
    for (const c of s.scene.cues) rows.push([beatValue(c.at, meter), `${c.block}${"text" in c && c.text ? ` “${c.text}”` : ""}${c.until !== undefined ? ` → b${beatValue(c.until, meter)}` : ""}`]);
    if (s.scene.type === "demo") {
      for (const k of s.scene.camera) rows.push([beatValue(k.at, meter), `camera → ${JSON.stringify(k.to)}`]);
      for (const m of s.scene.marks) rows.push([beatValue(m.at, meter), `mark ${JSON.stringify(m.on)}${m.label ? ` “${m.label}”` : ""}`]);
      for (const c of s.scene.clicks) rows.push([beatValue(c.at, meter), `click ${JSON.stringify(c.on)}`]);
      for (const w of s.scene.swaps) rows.push([beatValue(w.at, meter), `swap → ${w.shot}`]);
      for (const t of s.scene.typing) rows.push([beatValue(t.at, meter), `typing “${t.text.slice(0, 30)}…”`]);
    }
    for (const v of s.voices) rows.push([v.atBeat, `🗣 ${v.text.slice(0, 50)}`]);
    if (!rows.length) continue;
    L.push(`## ${s.index + 1}. ${s.id} — beat sheet`, "", "| beat | bar:beat | time | event |", "|---|---|---|---|");
    for (const [b, e] of rows.sort((a, c) => a[0] - c[0])) {
      const G = s.start + b, bar = Math.floor((G - tl.grid.downbeat) / meter) + 1, bb = (((G - tl.grid.downbeat) % meter) + meter) % meter + 1;
      L.push(`| ${b} | ${Number.isInteger(G) ? `${bar}:${bb}` : "off-beat"} | ${fmt(sec(frameOfBeat(tl.grid, G)))} | ${e.replace(/\|/g, " / ")} |`);
    }
    L.push("");
  }
  if (tl.warnings.length) L.push("## Warnings", "", ...tl.warnings.map((w) => `- ${w}`), "");
  return L.join("\n");
}

async function cmdCheck(p: Project) {
  const tl = timeline(p), found = lint(p, tl);
  const video = flag("video") ?? path.join(outDir(p), `${p.name}.mp4`);
  const L = [`# Check — ${p.name}`, ""];
  for (const f of found) L.push(`- **${f.level}** \`${f.where}\` ${f.msg}`);
  if (!found.length) L.push("- spec: no problems found");
  if (fs.existsSync(video)) {
    const ld = await loudness(video), al = await beatAlignment(video, tl);
    L.push("", `## ${rel(video)}`, "");
    if (ld) L.push(`- loudness ${ld.lufs} LUFS (target −14), peak ${ld.peak} dBFS${ld.lufs > -13 || ld.lufs < -15 ? "  ← off target: run render again (it masters)" : ""}`);
    else L.push("- no audio stream");
    if (al && !al.events) L.push("- picture changes on the beat: n/a (no sharp changes found)");
    else if (al) L.push(`- picture changes on the beat (±2 frames): ${al.onBeat}/${al.events} (${Math.round(al.share * 100)}%). Camera moves peak mid-move by design, so 100% is not the goal.`,
      ...al.worst.map((w) => `  - off-beat change at ${fmt(w.f / tl.grid.fps)} (${w.off > 0 ? "+" : ""}${w.off.toFixed(1)} frames)`));
  } else L.push("", `(no rendered file at ${rel(video)} — render first for audio/rhythm checks)`);
  L.push("", "Passing these checks does not mean the video works: watch it once with sound.");
  const report = path.join(outDir(p), "report.md");
  fs.writeFileSync(report, L.join("\n") + "\n");
  console.log(L.join("\n"));
  if (found.some((f) => f.level === "error")) process.exitCode = 1;
}

async function master(raw: string, out: string) {
  const probe = await run(["-i", raw], { quiet: true });
  const hasAudio = /Stream #.*Audio:/.test(probe.stderr);
  // two-pass loudnorm: measure first, then correct linearly (one pass undershoots on short videos)
  let af = "loudnorm=I=-14:TP=-1.5:LRA=11";
  if (hasAudio) {
    const m = await run(["-i", raw, "-af", "loudnorm=I=-14:TP=-1.5:LRA=11:print_format=json", "-f", "null", "-"], { quiet: true });
    const j = m.stderr.slice(m.stderr.lastIndexOf("{"));
    try {
      const v = JSON.parse(j.slice(0, j.indexOf("}") + 1));
      const nums = [v.input_i, v.input_tp, v.input_lra, v.input_thresh, v.target_offset].map(Number);
      if (m.code !== 0 || !nums.every(Number.isFinite)) af = "anull";            // silence or a failed measurement: leave the level alone
      else af = `loudnorm=I=-14:TP=-1.5:LRA=11:measured_I=${v.input_i}:measured_TP=${v.input_tp}:measured_LRA=${v.input_lra}:measured_thresh=${v.input_thresh}:offset=${v.target_offset}:linear=true`;
    } catch { /* fall back to one pass */ }
  }
  const args = ["-y", "-loglevel", "error", "-i", raw, "-vf", "scale=in_range=full:out_range=limited,format=yuv420p", "-color_range", "tv", "-colorspace", "bt709",
    "-color_primaries", "bt709", "-color_trc", "bt709", "-c:v", "libx264", "-preset", "slow", "-crf", "18",
    ...(hasAudio ? ["-af", af, "-ar", "48000", "-c:a", "aac", "-b:a", "192k"] : ["-an"]), "-movflags", "+faststart", out];
  const r = await run(args, { quiet: true });
  if (r.code !== 0) throw new Error("mastering failed: " + r.stderr.trim().split("\n").pop());
}

async function cmdRender(p: Project) {
  const props = writeProps(p), o = outDir(p), raw = path.join(o, "raw.mp4"), final = path.join(o, `${p.name}.mp4`);
  const extra = [flag("frames") ? `--frames=${flag("frames")}` : "", flag("scale") ? `--scale=${flag("scale")}` : "", flag("concurrency") ? `--concurrency=${flag("concurrency")}` : ""].filter(Boolean);
  await remotion(["render", "src/index.ts", "PRAI", raw, `--props=${props}`, `--public-dir=${p.pub}`, "--codec=h264", "--crf=16", "--audio-codec=aac", "--audio-bitrate=320k", ...extra]);
  if (flags.raw) return console.log(`rendered ${rel(raw)}`);
  await master(raw, final);
  fs.rmSync(raw, { force: true });
  console.log(`rendered and mastered ${rel(final)} (−14 LUFS, bt709)`);
}

async function cmdSheet(p: Project) {
  const tl = timeline(p), every = Number(flag("every", "4")), cols = Math.round(Number(flag("cols", "6")));
  if (!(every >= 0.25) || !(cols >= 1)) throw new Error("--every must be ≥ 0.25 beats and --cols ≥ 1");
  const scenes = flag("scene") ? tl.scenes.filter((s) => s.id === flag("scene")) : tl.scenes;
  if (!scenes.length) throw new Error(`no scene "${flag("scene")}"`);
  const frames: number[] = [], labels: string[] = [];
  for (const s of scenes) for (let b = 0; b < s.beats; b += every) {
    const f = frameOfBeat(tl.grid, s.start + b) + Number(flag("offset", "1"));        // a frame after the beat shows the landed pose
    frames.push(f); labels.push(`${fmt(f / tl.grid.fps)}  ${s.id} b${b}`);
  }
  const props = writeProps(p, { sheet: { frames, cols, labels } });
  const out = path.join(outDir(p), `sheet${flag("scene") ? "-" + flag("scene") : ""}.png`);
  await remotion(["still", "src/index.ts", "PRAI-Sheet", out, `--props=${props}`, `--public-dir=${p.pub}`, "--image-format=png"]);
  console.log(`contact sheet: ${rel(out)} (${frames.length} frames)`);
  return out;
}

async function cmdStill(p: Project) {
  const tl = timeline(p), t = Number(flag("time", "0")), frame = Math.max(0, Math.min(tl.totalFrames - 1, Math.round(t * tl.grid.fps)));
  const out = flag("out") ?? path.join(outDir(p), `${p.name}-${t}s.png`);
  await remotion(["still", "src/index.ts", "PRAI", out, `--props=${writeProps(p)}`, `--public-dir=${p.pub}`, `--frame=${frame}`, "--image-format=png", ...(flag("scale") ? [`--scale=${flag("scale")}`] : [])]);
  console.log(`still: ${rel(out)} (frame ${frame})`);
}

async function cmdGif(p: Project) {
  const src = flag("video") ?? path.join(outDir(p), `${p.name}.mp4`), from = flag("from", "0")!, to = flag("to", "6")!, width = flag("width", "960")!;
  const out = flag("out") ?? path.join(outDir(p), `${p.name}-${from}-${to}.gif`);
  const vf = `fps=${flag("fps", "15")},scale=${width}:-1:flags=lanczos,split[a][b];[a]palettegen=stats_mode=diff[p];[b][p]paletteuse=dither=sierra2_4a`;
  const r = await run(["-y", "-loglevel", "error", "-ss", from, "-to", to, "-i", src, "-vf", vf, out], { quiet: true });
  if (r.code !== 0) throw new Error(r.stderr);
  console.log(`gif: ${rel(out)}`);
}

async function cmdReview(p: Project) {
  const kind = pos[2] as Kind;
  if (!KINDS.includes(kind)) throw new Error(`review kind must be one of: ${KINDS.join(", ")}`);
  const images: string[] = [];
  if (kind === "frames") images.push(flag("sheet") ?? (await cmdSheet(p)));
  const ledgerFile = path.join(p.dir, "reviews", "ledger.md"), refsBrief = path.join(outDir(p), "refs-brief.md");
  const vars = {
    project: p.name, spec: JSON.stringify(p.raw, null, 1), plan: planMarkdown(p),
    ledger: fs.existsSync(ledgerFile) ? fs.readFileSync(ledgerFile, "utf8") : "(no earlier rounds)",
    brief: fs.existsSync(refsBrief) ? fs.readFileSync(refsBrief, "utf8") : "(run `prai refs brief` first)",
    lang: p.spec.video.lang, focus: flag("focus", "")!,
  };
  await runReview(p, kind, buildPrompt(kind, vars), images, { max: flag("max") ? Number(flag("max")) : undefined, effort: flag("effort"), dry: !!flags.dry });
}

function cmdInit() {
  if (!name) throw new Error("usage: prai init <name>");
  const dest = path.join(ROOT, "projects", name);
  if (fs.existsSync(dest)) throw new Error(`projects/${name} already exists`);
  fs.cpSync(path.join(ROOT, "templates", "starter"), dest, { recursive: true });
  const f = path.join(dest, "prai.json");
  fs.writeFileSync(f, fs.readFileSync(f, "utf8").replace(/__NAME__/g, name));
  console.log(`created projects/${name}. Next:\n  1. edit projects/${name}/capture.json (your app's URL and the screens to shoot)\n  2. npm run prai -- capture ${name}\n  3. edit prai.json scenes, then: npm run prai -- all ${name}`);
}

const HELP = `prai — beat-synced demo videos from a JSON spec

  init <name>                 new project from templates/starter
  capture <p> [--only a,b]    shoot screens + measure elements (capture.json)
  music <p> [--synth]         download music.url, or generate a CC0 groove
  beat <p>                    measure BPM, first beat, bar phase → prai.lock.json
  voice <p>                   narrate every "say" line (edge / command / file) → lock
  plan <p>                    scene table + beat sheets → out/<p>/plan.md
  check <p>                   lint the spec; loudness + beat alignment of the render
  studio <p>                  open Remotion Studio with this project
  render <p> [--raw]          render + master (−14 LUFS, bt709) → out/<p>/<p>.mp4
  sheet <p> [--every 4]       contact sheet of frames → out/<p>/sheet.png
  still <p> --time 12.5       one frame as PNG (thumbnails, banners)
  gif <p> --from 0 --to 6     a GIF from the render (README, PRs, chats)
  review <p> <kind>           Codex review: ${KINDS.join(" | ")} (round-capped, ledger)
  refs <sub> <p> …            reference library: add | list | research | frames | brief | check
  all <p> [--no-voice]        music → beat → voice → check → render (stops on errors)`;

async function main() {
  if (!cmd || cmd === "help" || flags.help) return console.log(HELP);
  if (cmd === "init") return cmdInit();
  if (cmd === "refs") return refsCommand(pos.slice(1), flags);
  if (!name) throw new Error(`usage: prai ${cmd} <project>`);
  const p = load(name);
  switch (cmd) {
    case "capture": {
      const planFile = path.join(p.dir, "capture.json");
      if (!fs.existsSync(planFile)) throw new Error(`no ${rel(planFile)}`);
      await capture(p.dir, JSON.parse(fs.readFileSync(planFile, "utf8")) as CapturePlan, flag("only")?.split(","));
      return;
    }
    case "music": return cmdMusic(p);
    case "beat": return cmdBeat(p);
    case "voice": return cmdVoice(p);
    case "plan": { const md = planMarkdown(p); fs.writeFileSync(path.join(outDir(p), "plan.md"), md); return console.log(md); }
    case "check": return cmdCheck(p);
    case "studio": return remotion(["studio", "src/index.ts", `--props=${writeProps(p)}`, `--public-dir=${p.pub}`]);
    case "render": return cmdRender(p);
    case "sheet": return void (await cmdSheet(p));
    case "gif": return cmdGif(p);
    case "still": return cmdStill(p);
    case "review": return cmdReview(p);
    case "all": {
      if (p.spec.music && !fs.existsSync(path.join(p.pub, p.spec.music.src))) await cmdMusic(p);
      const q = load(name);
      if (q.spec.music && !q.lock.music && (q.spec.music.bpm === undefined || q.spec.music.offset === undefined)) await cmdBeat(q);
      if (q.spec.scenes.some((s) => s.say)) {
        if (flags["no-voice"]) console.warn("--no-voice: rendering without narration (lengths use estimates)");
        else await cmdVoice(load(name));
      }
      const r = load(name);
      if (flags["no-voice"]) r.lock = { ...r.lock, voice: {} };                // existing recordings are not played either
      await cmdCheck(r);
      if (process.exitCode) throw new Error("prai check found errors — fix them first (out/" + r.name + "/report.md)");
      return cmdRender(r);
    }
    default: throw new Error(`unknown command "${cmd}"\n\n${HELP}`);
  }
}

main().catch((e) => { console.error(`\n✖ ${e.message ?? e}`); process.exit(1); });
